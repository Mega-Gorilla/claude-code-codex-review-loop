"""C-08 active host protocolとstep engine（Phase 8）。

Controller CLIはClaude Code sessionの子processであり、親のLLM turnを呼び戻せない。
そのためcore engineはClaudeを起動せず、`advance`で次の`HOST_ACTION`を返し、active hostが
自分のcontextで実行して`submit`で結果を返す**step engine**とする（implementation plan
Section 2の制御反転）。この構造は全workflowの前提で、覆すと全体の書き直しになる。

**同一runに対する制御経路は`advance`と`submit`の2つだけ**である（AC-C08-03）。`persist`は
`advance`が返す`PersistRequired`（C-01の`PersistRecord`）の実行であり、独立した制御経路では
ない。`advance`は`HOST_ACTION`と`AWAIT_USER`の両方を払い出し、`submit`は両者の応答を同一の
entry pointで受ける。

正本: registryはADR-0014、step engineはADR-0015、`PersistRecord`はADR-0017、
`AWAIT_USER`搬送路はADR-0018。adapterとprocess境界（AC-C08-04 / 06）は後続PRが追加する。
"""

